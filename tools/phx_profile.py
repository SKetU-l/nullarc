#!/usr/bin/env python3
"""Validate captured DRM topology and reproduce the shared HP header. No GPU writes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROFILE = ROOT / 'hardware/profiles/hp-760m.json'
HEADER = ROOT / 'src/amd/phx_hp_760m.h'
ELITEBOOK_PROFILE = ROOT / 'hardware/profiles/elitebook-845-g10-780m.json'
ELITEBOOK_HEADER = ROOT / 'src/amd/phx_elitebook_780m.h'


def integer(value, lo, hi, name):
    if type(value) is not int or not lo <= value <= hi:
        raise ValueError(f'{name}: expected integer in [{lo}, {hi}]')
    return value


def validate(p):
    if not isinstance(p, dict) or p.get('format') != 1 or type(p.get('format')) is not int:
        raise ValueError('format must be integer 1')
    pci = p['pci']
    for key in ('vendor', 'device', 'revision', 'subvendor', 'subdevice'):
        integer(pci[key], 0, 255 if key == 'revision' else 65535, f'pci.{key}')
    if pci['vendor'] != 0x1002:
        raise ValueError('expected AMD vendor 0x1002')
    se = integer(p['num_shader_engines'], 1, 4, 'num_shader_engines')
    sa = integer(p['num_shader_arrays_per_engine'], 1, 4, 'num_shader_arrays_per_engine')
    cu = integer(p['num_cu_per_sh'], 1, 32, 'num_cu_per_sh')
    rb = integer(p['num_rb_pipes'], 1, 32, 'num_rb_pipes')
    integer(p['enabled_rb_pipes_mask'], 1, (1 << rb) - 1, 'enabled_rb_pipes_mask')
    integer(p['cu_active_number'], 1, se * sa * cu, 'cu_active_number')
    bitmap = p['cu_bitmap']
    if not isinstance(bitmap, list) or len(bitmap) != 4:
        raise ValueError('cu_bitmap must be a 4x4 matrix')
    count = 0
    for i, row in enumerate(bitmap):
        if not isinstance(row, list) or len(row) != 4:
            raise ValueError('cu_bitmap must be a 4x4 matrix')
        for j, mask in enumerate(row):
            integer(mask, 0, (1 << cu) - 1, f'cu_bitmap[{i}][{j}]')
            if mask and (i >= se or j >= sa):
                raise ValueError('enabled CUs outside physical shader topology')
            count += bin(mask).count('1')
    if count != p['cu_active_number']:
        raise ValueError('CU population differs from cu_active_number')
    return p


def load(path):
    def unique(pairs):
        d = {}
        for key, value in pairs:
            if key in d:
                raise ValueError(f'duplicate key: {key}')
            d[key] = value
        return d
    return validate(json.loads(Path(path).read_text(), object_pairs_hook=unique))


def render(p, elitebook=False):
    pci = p['pci']
    identity = ', '.join(f'0x{pci[k]:x}u' for k in ('vendor', 'device', 'revision', 'subvendor', 'subdevice'))
    dimensions = ', '.join(str(p[k]) + 'u' for k in ('num_shader_engines', 'num_shader_arrays_per_engine',
                          'num_cu_per_sh', 'num_rb_pipes', 'enabled_rb_pipes_mask', 'cu_active_number'))
    rows = ',\n        '.join('{' + ', '.join(f'0x{x:x}u' for x in row) + '}' for row in p['cu_bitmap'])
    source = ELITEBOOK_PROFILE.name if elitebook else PROFILE.name
    symbol = 'phx_elitebook_780m' if elitebook else 'phx_hp_760m'
    guard = symbol.upper() + '_H'
    dependency = ('/* Included by phx_topology.h after the wire type. */'
                  if elitebook else '#include "phx_topology.h"')
    provenance = ('Read-only Linux AMDGPU_INFO capture, 2026-11-12; not verified Tahoe bring-up.'
                  if elitebook else 'User-supplied capture, not live fuse discovery or verified bring-up.')
    return f'''/* SPDX-License-Identifier: MIT
 * Generated by tools/phx_profile.py; source: hardware/profiles/{source}.
 * {provenance}
 */
#ifndef {guard}
#define {guard}
{dependency}
static const struct phx_topology {symbol} = {{
    PHX_TOPOLOGY_VERSION, PHX_TOPOLOGY_CAPTURED,
    {identity},
    {dimensions},
    {{
        {rows}
    }},
    {{0, 0, 0}}
}};
#endif
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('profile', nargs='?', type=Path, default=PROFILE)
    group = ap.add_mutually_exclusive_group()
    group.add_argument('--write-header', action='store_true')
    group.add_argument('--check', action='store_true')
    args = ap.parse_args()
    try:
        p = load(args.profile)
        elitebook = args.profile.resolve() == ELITEBOOK_PROFILE.resolve()
        header = ELITEBOOK_HEADER if elitebook else HEADER
        content = render(p, elitebook)
        if args.write_header:
            if args.profile.resolve() not in (PROFILE.resolve(), ELITEBOOK_PROFILE.resolve()):
                raise ValueError('only checked-in profiles may generate their headers')
            header.write_text(content)
        if args.check and header.read_text() != content:
            raise ValueError('stale generated header; run tools/phx_profile.py --write-header')
        print(f'valid capture: {p["cu_active_number"]} CUs; physical masks preserved; runtime untested')
    except (ValueError, KeyError, TypeError, OSError) as e:
        ap.exit(1, f'profile: {e}\n')


if __name__ == '__main__':
    main()
